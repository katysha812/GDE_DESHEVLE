
from db import Session
from models import Магазины, Категории, Товары


session = Session()

try:
    # -------------------------
    # Создаём магазины
    # -------------------------

    пятерочка = session.query(Магазины).filter_by(
        название="Пятёрочка",
        адрес="ул. Ленина, 10"
    ).first()

    if пятерочка is None:
        пятерочка = Магазины(
            название="Пятёрочка",
            адрес="ул. Ленина, 10",
            город="Москва",
            телефон="+79990000001"
        )
        session.add(пятерочка)

    магнит = session.query(Магазины).filter_by(
        название="Магнит",
        адрес="ул. Гагарина, 25"
    ).first()

    if магнит is None:
        магнит = Магазины(
            название="Магнит",
            адрес="ул. Гагарина, 25",
            город="Москва",
            телефон="+79990000002"
        )
        session.add(магнит)

    # -------------------------
    # Создаём категории
    # -------------------------

    названия_категорий = [
        "Молочные продукты",
        "Хлебобулочные изделия",
        "Бакалея"
    ]

    категории = {}

    for название in названия_категорий:
        категория = session.query(Категории).filter_by(
            название=название
        ).first()

        if категория is None:
            категория = Категории(название=название)
            session.add(категория)

        категории[название] = категория

    # Сохраняем, чтобы получить ID
    session.flush()

    # -------------------------
    # Добавляем товары
    # -------------------------

    тестовые_товары = [
        {
            "название": "Молоко",
            "цена": 89.90,
            "магазин": пятерочка,
            "категория": категории["Молочные продукты"]
        },
        {
            "название": "Хлеб",
            "цена": 45.00,
            "магазин": пятерочка,
            "категория": категории["Хлебобулочные изделия"]
        },
        {
            "название": "Яйца",
            "цена": 110.00,
            "магазин": пятерочка,
            "категория": категории["Молочные продукты"]
        },
        {
            "название": "Молоко",
            "цена": 79.90,
            "магазин": магнит,
            "категория": категории["Молочные продукты"]
        },
        {
            "название": "Хлеб",
            "цена": 39.90,
            "магазин": магнит,
            "категория": категории["Хлебобулочные изделия"]
        },
        {
            "название": "Сахар",
            "цена": 75.50,
            "магазин": магнит,
            "категория": категории["Бакалея"]
        }
    ]

    for данные in тестовые_товары:
        товар = session.query(Товары).filter_by(
            название=данные["название"],
            id_магазина=данные["магазин"].id
        ).first()

        if товар is None:
            товар = Товары(
                название=данные["название"],
                цена=данные["цена"],
                магазин=данные["магазин"],
                категория=данные["категория"],
                единица_измерения="шт."
            )

            session.add(товар)

    session.commit()

    print("Тестовые данные успешно добавлены!")

except Exception as e:
    session.rollback()
    print(f"Ошибка при заполнении базы: {e}")

finally:
    session.close()
